/**
 * 查找标题对应的知识点 key。
 *
 * @param haystack  课时标题（核心课名 + 完整标题）
 * @param topicKeys 已知知识点的 key 集合（用于校验别名有效）
 * @returns 命中的知识点 key，没有则返回 null
 */
export function matchAliasKey(haystack, topicKeys, coreTitle = "") {
  // 先跑正则形式的课型别名（「练习六」这类）。
  // `^` 锚定的模式只认 coreTitle——它要匹配的是**整个课名**，
  // 而不是把 coreTitle 与 fullTitle 拼起来后的长串。
  for (const entry of MATH_PATTERN_ALIASES) {
    if (!topicKeys.has(entry.key)) continue;
    if (entry.pattern.test(coreTitle)) return entry.key;
    if (!entry.pattern.source.startsWith("^")) {
      if (entry.pattern.test(haystack)) return entry.key;
    }
  }

  let best = null;
  let bestLength = 0;
  for (const [alias, key] of Object.entries(MATH_ALIASES)) {
    if (!haystack.includes(alias)) continue;
    if (!topicKeys.has(key)) continue;
    // 别名越长越具体，优先。
    const score = alias.length + (key.length === 2 ? 0.5 : 0);
    if (score > bestLength) {
      best = key;
      bestLength = score;
    }
  }
  return best;
}
