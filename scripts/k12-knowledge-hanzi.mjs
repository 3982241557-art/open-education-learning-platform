/**
 * 判断一个课名是不是「非课文课型」。
 *
 * @param {string} title 课名
 */
export function isNonTextbookLesson(title) {
  const name = String(title ?? "");
  return NON_TEXTBOOK_KINDS.some((kind) => name.includes(kind));
}

/**
 * 查一篇课文的真实生字。
 *
 * 匹配策略（从严到松）：
 *
 * 1. **精确匹配**课名；
 * 2. 课名去掉「（生字）」「1」「2」「·下」等后缀后再匹配；
 * 3. 课名以某个有生字的课文**开头**（处理「古诗三首_元日1」这种）。
 *
 * @param {string} title 课名
 * @returns {LessonHanzi | null}
 */
export function matchLessonHanzi(title) {
  const raw = String(title ?? "").trim();
  if (!raw) return null;

  // ① 精确。
  if (LESSON_HANZI[raw]) return LESSON_HANZI[raw];

  // ② 逐步剥掉修饰后缀。
  const stripped = raw
    .replace(/[（(][^）)]*[）)]/g, "")
    .replace(/[·・_]\s*[^·・_]*$/, "")
    .replace(/\s*\d+$/, "")
    .trim();

  if (stripped && LESSON_HANZI[stripped]) return LESSON_HANZI[stripped];

  // ②.5 「古诗三首_元日」这类「组名_课文名」——取后半段再试。
  const afterSeparator = raw.split(/[·・_]/).filter(Boolean).pop();
  if (afterSeparator && afterSeparator !== raw) {
    const tail = afterSeparator
      .replace(/[（(][^）)]*[）)]/g, "")
      .replace(/\s*\d+$/, "")
      .trim();
    if (tail && LESSON_HANZI[tail]) return LESSON_HANZI[tail];
  }

  // ③ 前缀匹配（取最长命中，避免「古诗三首」抢走「古诗三首_元日」）。
  let best = null;
  let bestLen = 0;
  for (const [key, value] of Object.entries(LESSON_HANZI)) {
    if (key.length <= bestLen) continue;
    if (raw.startsWith(key) || stripped.startsWith(key)) {
      best = value;
      bestLen = key.length;
    }
  }
  return best;
}
