/**
 * 合并后的完整题库。
 *
 * 主表 36 个 + 补充卷 A 30 个 + 补充卷 B 57 个 = **123 个知识点**。
 */
export const MATH_CONCEPT_BANK = {
  ...MATH_CONCEPT_BANK_BASE,
  ...MATH_CONCEPT_BANK_EXT_A,
  ...MATH_CONCEPT_BANK_EXT_B,
};

/**
 * 取得某个知识点的三道真实题（概念辨析 / 迁移应用 / 变式应用）。
 *
 * @param {string} topicTitle 知识点标题
 * @returns {{concept: object, transfer: object, variant: object} | null}
 */
export function getMathConceptBank(topicTitle) {
  const bank = MATH_CONCEPT_BANK[topicTitle];
  if (!bank) return null;

  // 主表的条目自带 concept + transfer；
  // 补充卷的条目是**单题**形态，需要补齐成三题。
  const concept = bank.concept ?? bank;
  const transfer = bank.transfer ?? bank;

  // 变式题：把概念题的背景换掉，考同一个知识点。
  const variant = {
    ...concept,
    question: `换个问法再考一次：${concept.question}`,
    options: [...concept.options],
    correctIndex: concept.correctIndex,
    explanation: `${concept.explanation}\n\n**换个问法还能做对，说明是真的掌握了。**`,
  };

  return { concept, transfer, variant };
}
