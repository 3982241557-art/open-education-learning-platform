def hooks_for(resource_id: str) -> dict[str, dict[str, Any]]:
    """取某门课的定制钩子。

    Args:
        resource_id: 资源 id。

    Returns:
        节点主键 → 钩子 的映射。没有定制题的课程返回空字典。
    """
    return HOOKS.get(resource_id, {})


def apply_hooks(
    resource_id: str,
    nodes: list[dict[str, Any]],
) -> list[dict[str, Any]]:
    """把定制钩子挂到某门课的节点上。

    匹配用「时间戳数值 + 关键词」双重判定——**不**用字符串主键。
    原因是 Python 把 JSON 里的 ``704`` 读成 ``704.0``，而 JS 读成
    ``704``；直接比字符串会漏掉一部分节点。

    Args:
        resource_id: 资源 id。
        nodes: 该资源的 ``interactive_nodes`` 列表（原地修改）。

    Returns:
        挂上钩子的节点列表（同一个对象）。
    """
    hooks = hooks_for(resource_id)
    if not hooks:
        return nodes

    # 先把主键索引成「(时间戳, 关键词)」形式。
    index: dict[tuple[float, str], dict[str, Any]] = {}
    for key, hook in hooks.items():
        raw_ts, _, keyword = key.partition("::")
        try:
            timestamp = float(raw_ts)
        except ValueError:
            continue
        index[(timestamp, keyword.strip())] = hook

    for node in nodes:
        try:
            timestamp = float(node.get("timestamp", 0))
        except (TypeError, ValueError):
            continue
        keyword = str(node.get("keyword", "")).strip()
        hook = index.get((timestamp, keyword))
        if hook:
            node["predict_hook"] = dict(hook)

    return nodes


def main() -> int:
    """打印钩子统计——确认题库是完整的。"""
    total = sum(len(hooks) for hooks in HOOKS.values())
    print(f"定制钩子：{len(HOOKS)} 门课 · {total} 道题")
    for course_id, hooks in HOOKS.items():
        print(f"  {course_id}: {len(hooks)} 道")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
